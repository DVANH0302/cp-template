using ll = long long;

#define rep(i, a, b) for (int i = (a); i < (b); ++i)
#define trav(it, v) for (auto &it : v)
#define all(v) (v).begin(), (v).end()

const int mod = 1000000000 + 7;

void solve() {
  int n;
  cin >> n;
  vector<int> a(n);

  trav(ai, a) { cin >> ai; }
  sort(all(a));

  for (int i = 1; i <= n / 2; i++) {
    cout << a[i] << " " << a[0] << "\n";
  }
}

int main() {
  ios::sync_with_stdio(false);
  cin.tie(0);
  cout.tie(0);

  int t;
  cin >> t;
  while (t--)

    solve();
}